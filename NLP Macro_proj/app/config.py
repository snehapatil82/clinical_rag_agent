from pathlib import Path
from typing import Literal, Optional
from dotenv import load_dotenv
from pydantic_settings import BaseSettings, SettingsConfigDict
from pydantic import Field

# Determine workspace base directory
PROJECT_ROOT = Path(__file__).resolve().parent.parent

# Explicitly load .env into os.environ
load_dotenv(PROJECT_ROOT / ".env", override=True)


class Settings(BaseSettings):
    """Application configuration settings."""

    model_config = SettingsConfigDict(
        env_file=str(PROJECT_ROOT / ".env"),
        env_file_encoding="utf-8",
        extra="ignore",
    )

    # LLM Settings
    LLM_PROVIDER: Literal["groq", "openai", "gemini", "mock"] = Field(
        default="groq",
        description="Active LLM provider backend"
    )
    GROQ_API_KEY: Optional[str] = Field(default=None, description="Groq API key")
    OPENAI_API_KEY: Optional[str] = Field(default=None, description="OpenAI API key")
    GEMINI_API_KEY: Optional[str] = Field(default=None, description="Gemini API key")

    LLM_MODEL: str = Field(
        default="openai/gpt-oss-120b",
        description="Default model name for the LLM provider"
    )
    LLM_TEMPERATURE: float = Field(
        default=0.1,
        ge=0.0,
        le=1.0,
        description="Sampling temperature for grounded generation (low for factual adherence)"
    )
    LLM_MAX_TOKENS: int = Field(
        default=1024,
        gt=0,
        description="Maximum tokens generated by the LLM"
    )

    # Embedding Model Settings
    EMBEDDING_MODEL_NAME: str = Field(
        default="sentence-transformers/all-MiniLM-L6-v2",
        description="HuggingFace model ID for SentenceTransformers"
    )
    EMBEDDING_DEVICE: str = Field(
        default="cpu",
        description="Compute device for embeddings: 'cpu', 'cuda', or 'mps'"
    )
    EMBEDDING_DIMENSION: int = Field(
        default=384,
        description="Output embedding dimension for all-MiniLM-L6-v2"
    )

    # Document Chunking Settings
    CHUNK_SIZE: int = Field(
        default=600,
        gt=50,
        description="Target chunk size in characters"
    )
    CHUNK_OVERLAP: int = Field(
        default=100,
        ge=0,
        description="Sliding window overlap between consecutive chunks"
    )

    # Retrieval Settings
    TOP_K: int = Field(
        default=4,
        ge=1,
        le=20,
        description="Number of top relevant chunks to retrieve from FAISS"
    )
    SIMILARITY_THRESHOLD: float = Field(
        default=0.38,
        ge=0.0,
        le=1.0,
        description="Minimum cosine similarity required to consider evidence relevant"
    )

    # Paths (relative or absolute)
    DATA_RAW_DIR: Path = Field(
        default=PROJECT_ROOT / "data" / "raw",
        description="Directory for source clinical documents"
    )
    DATA_PROCESSED_DIR: Path = Field(
        default=PROJECT_ROOT / "data" / "processed",
        description="Directory for cached chunks and intermediate data"
    )
    VECTOR_STORE_DIR: Path = Field(
        default=PROJECT_ROOT / "vector_store",
        description="Directory where FAISS index and metadata.json are persisted"
    )
    EVALUATION_DATA_PATH: Path = Field(
        default=PROJECT_ROOT / "data" / "evaluation" / "questions.json",
        description="Path to ground-truth evaluation benchmark JSON"
    )

    def ensure_directories(self) -> None:
        """Create necessary directories if they do not exist."""
        self.DATA_RAW_DIR.mkdir(parents=True, exist_ok=True)
        self.DATA_PROCESSED_DIR.mkdir(parents=True, exist_ok=True)
        self.VECTOR_STORE_DIR.mkdir(parents=True, exist_ok=True)
        self.EVALUATION_DATA_PATH.parent.mkdir(parents=True, exist_ok=True)


# Singleton instance
settings = Settings()
settings.ensure_directories()
